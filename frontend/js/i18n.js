/**
 * Universal text localization helper
 */
window.localize = function(text, lang) {
  if (!text) return text;
  lang = lang || window.appState?.state?.lang || 'mr';

  // 1. Direct dictionary key match (for mr, hi, and en)
  var dict = window.GRAMSETU_I18N && window.GRAMSETU_I18N[lang];
  if (dict && dict[text] !== undefined) return dict[text];

  // If key exists in mr dictionary as fallback
  if (window.GRAMSETU_I18N && window.GRAMSETU_I18N['mr'] && window.GRAMSETU_I18N['mr'][text] !== undefined) {
    if (lang === 'mr') return window.GRAMSETU_I18N['mr'][text];
  }

  // If language is Marathi and text is not a dictionary key, it is already Marathi text
  if (lang === 'mr') return text;

  // 2. Exact phrase match
  var phrases = window.GRAMSETU_PHRASES;
  if (phrases && phrases[text] && phrases[text][lang]) {
    return phrases[text][lang];
  }

  // 3. Trimmed phrase match
  var trimmed = String(text).trim();
  if (phrases && phrases[trimmed] && phrases[trimmed][lang]) {
    return phrases[trimmed][lang];
  }

  // 4. Substring replacement
  var keys = window.GRAMSETU_SORTED_KEYS;
  if (keys) {
    var res = String(text);
    for (var i = 0; i < keys.length; i++) {
      var k = keys[i];
      if (res.indexOf(k) !== -1 && phrases[k] && phrases[k][lang]) {
        res = res.split(k).join(phrases[k][lang]);
      }
    }
    return res;
  }

  return text;
};
